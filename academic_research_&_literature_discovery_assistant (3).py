def upload_and_process(file):

    if file is None:

        return (
            "❌ No file uploaded.",
            "Please upload a research PDF."
        )

    try:

        file_path = str(file)

        print(
            f"Processing file: {file_path}"
        )

        # ==================================
        # Metadata
        # ==================================
        #
        # No manual title or author input.
        # The document itself will be used as
        # the source.
        #

        metadata = {
            "source": os.path.basename(
                file_path
            )
        }

        # ==================================
        # VALIDATION
        # ==================================

        validation = (
            assistant.validator.validate_file(
                file_path,
                metadata=None
            )
        )

        if not validation.valid:

            errors = "\n".join(
                [
                    f"• {error}"
                    for error in validation.errors
                ]
            )

            return (
                "❌ DOCUMENT REJECTED\n\n"
                + errors,

                "❌ Document was NOT indexed."
            )

        # ==================================
        # INDEXING
        # ==================================

        result = (
            assistant.ingest_document(
                file_path,
                metadata=metadata
            )
        )

        if not result["indexed"]:

            errors = "\n".join(
                result.get(
                    "errors",
                    ["Unknown indexing error."]
                )
            )

            return (
                "❌ INDEXING FAILED\n\n"
                + errors,

                "❌ Document was NOT stored."
            )

        return (
            "✅ DOCUMENT ACCEPTED\n\n"
            "The document passed validation.",

            (
                "✅ INDEXING SUCCESSFUL\n\n"
                f"File: {os.path.basename(file_path)}\n"
                f"Chunks: {result['chunks']}\n"
                "Stored in ChromaDB."
            )
        )

    except Exception as e:

        return (
            "❌ SYSTEM ERROR\n\n"
            f"{type(e).__name__}: {str(e)}",

            "The document could not be processed."
        )

