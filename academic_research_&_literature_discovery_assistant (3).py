import os
import hashlib


class DocumentValidator:

    def __init__(self):
        self.supported_extensions = settings.SUPPORTED_EXTENSIONS

    def validate_file(self, file_path: str) -> dict:

        result = {
            "file": file_path,
            "valid": True,
            "errors": []
        }

        # 1. File exists
        if not os.path.exists(file_path):
            result["valid"] = False
            result["errors"].append("File does not exist.")
            return result

        # 2. File extension
        extension = os.path.splitext(file_path)[1].lower()

        if extension not in self.supported_extensions:
            result["valid"] = False
            result["errors"].append(
                f"Unsupported file format: {extension}"
            )

        # 3. Empty file
        if os.path.getsize(file_path) == 0:
            result["valid"] = False
            result["errors"].append("File is empty.")

        return result

"""## 5. Content Quality Validation

After validating the file itself, validate the extracted content to ensure that the document contains enough readable text to be processed by the RAG pipeline.
"""

class DocumentValidator:

    def __init__(self):

        self.supported_extensions = [
            ".pdf"
        ]

        self.min_text_length = 100

    def calculate_hash(self, file_path):

        sha256 = hashlib.sha256()

        with open(
            file_path,
            "rb"
        ) as file:

            for block in iter(
                lambda: file.read(4096),
                b""
            ):

                sha256.update(block)

        return sha256.hexdigest()

    def validate_file(
        self,
        file_path,
        metadata=None
    ):

        result = DocumentValidationResult()

        # ==================================
        # 1. File exists
        # ==================================

        if not os.path.exists(file_path):

            result.add_error(
                "File does not exist."
            )

            return result

        # ==================================
        # 2. Supported format
        # ==================================

        extension = os.path.splitext(
            file_path
        )[1].lower()

        if extension not in self.supported_extensions:

            result.add_error(
                f"Unsupported format: {extension}"
            )

            return result

        # ==================================
        # 3. Empty file
        # ==================================

        if os.path.getsize(
            file_path
        ) == 0:

            result.add_error(
                "Document is empty."
            )

            return result

        # ==================================
        # 4. Validate and extract PDF
        # ==================================

        extracted_text = ""

        try:

            reader = PdfReader(
                file_path
            )

            if len(reader.pages) == 0:

                result.add_error(
                    "PDF contains no pages."
                )

                return result

            for page in reader.pages:

                page_text = (
                    page.extract_text()
                )

                if page_text:

                    extracted_text += (
                        page_text + "\n"
                    )

        except Exception as e:

            result.add_error(
                f"Corrupted PDF: {str(e)}"
            )

            return result

        # ==================================
        # 5. Extractable text validation
        # ==================================

        clean_text = (
            extracted_text.strip()
        )

        if len(clean_text) < self.min_text_length:

            result.add_error(
                "Insufficient extractable text."
            )

        return result

"""## 6. Document Text Extraction

Extract readable text from supported documents. PDF files are processed using PyPDF, while TXT, CSV, and Excel files are also supported.
"""

from pypdf import PdfReader
import pandas as pd


class DocumentExtractor:

    @staticmethod
    def extract(file_path: str) -> str:

        extension = os.path.splitext(file_path)[1].lower()

        # PDF
        if extension == ".pdf":

            reader = PdfReader(file_path)

            pages = []

            for page in reader.pages:

                text = page.extract_text()

                if text:
                    pages.append(text)

            return "\n".join(pages)

        # TXT
        elif extension == ".txt":

            with open(
                file_path,
                "r",
                encoding="utf-8",
                errors="ignore"
            ) as file:

                return file.read()

        # CSV
        elif extension == ".csv":

            df = pd.read_csv(file_path)

            return df.to_string(index=False)

        # Excel
        elif extension == ".xlsx":

            df = pd.read_excel(file_path)

            return df.to_string(index=False)

        else:

            raise ValueError(
                f"Unsupported file type: {extension}"
            )

