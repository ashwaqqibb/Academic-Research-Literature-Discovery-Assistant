class ResearchAssistantService:

    def __init__(self):

        # Embedding model
        self.embedding_model = EmbeddingModel()

        # Document validation
        self.validator = DocumentValidator()

        # ChromaDB
        self.chroma_manager = ChromaManager()

        # LLM / RAG
        self.llm = LLMClient()

        # Track indexed documents
        self.indexed_hashes = set()

        print("✅ Research Assistant Service initialized.")

    # =========================================================
    # DOCUMENT INGESTION
    # =========================================================

    def ingest_document(
        self,
        file_path,
        metadata=None
    ):
        """
        Validate, extract, clean, chunk, embed,
        and store a research document in ChromaDB.
        """

        errors = []

        try:

            # -------------------------------------------------
            # 1. Validate
            # -------------------------------------------------

            validation_result = (
                self.validator.validate_file(
                    file_path,
                    metadata=metadata
                )
            )

            if not validation_result.valid:

                return {
                    "indexed": False,
                    "errors": validation_result.errors,
                    "chunks": 0
                }

            # -------------------------------------------------
            # 2. Duplicate detection
            # -------------------------------------------------

            document_hash = (
                self.validator.calculate_hash(
                    file_path
                )
            )

            if document_hash in self.indexed_hashes:

                return {
                    "indexed": False,
                    "errors": [
                        "Duplicate document detected."
                    ],
                    "chunks": 0
                }

            # -------------------------------------------------
            # 3. Extract text
            # -------------------------------------------------

            text = self._extract_text(
                file_path
            )

            if not text or not text.strip():

                return {
                    "indexed": False,
                    "errors": [
                        "No extractable text found."
                    ],
                    "chunks": 0
                }

            # -------------------------------------------------
            # 4. Clean text
            # -------------------------------------------------

            cleaned_text = self._clean_text(
                text
            )

            # -------------------------------------------------
            # 5. Split into chunks
            # -------------------------------------------------

            chunks = self._create_chunks(
                cleaned_text
            )

            if not chunks:

                return {
                    "indexed": False,
                    "errors": [
                        "No text chunks were created."
                    ],
                    "chunks": 0
                }

            # -------------------------------------------------
            # 6. Generate embeddings
            # -------------------------------------------------

            embeddings = []

            for chunk in chunks:

                embedding = (
                    self.embedding_model.encode(
                        chunk
                    )
                )

                embeddings.append(
                    embedding
                )

            # -------------------------------------------------
            # 7. Prepare ChromaDB data
            # -------------------------------------------------

            document_name = os.path.basename(
                file_path
            )

            document_id = (
                document_hash[:16]
            )

            ids = []

            metadatas = []

            for i in range(
                len(chunks)
            ):

                ids.append(
                    f"{document_id}_chunk_{i}"
                )

                chunk_metadata = {
                    "source": document_name,
                    "document_id": document_id,
                    "chunk_id": i
                }

                if metadata:

                    chunk_metadata.update(
                        metadata
                    )

                metadatas.append(
                    chunk_metadata
                )

            # -------------------------------------------------
            # 8. Store in ChromaDB
            # -------------------------------------------------

            self.chroma_manager.collection.add(
                ids=ids,
                documents=chunks,
                embeddings=embeddings,
                metadatas=metadatas
            )

            # -------------------------------------------------
            # 9. Mark document as indexed
            # -------------------------------------------------

            self.indexed_hashes.add(
                document_hash
            )

            return {
                "indexed": True,
                "errors": [],
                "chunks": len(chunks),
                "document_id": document_id
            }

        except Exception as e:

            return {
                "indexed": False,
                "errors": [
                    f"{type(e).__name__}: {str(e)}"
                ],
                "chunks": 0
            }

    # =========================================================
    # TEXT EXTRACTION
    # =========================================================

    def _extract_text(
        self,
        file_path
    ):

        extension = os.path.splitext(
            file_path
        )[1].lower()

        # PDF
        if extension == ".pdf":

            reader = PdfReader(
                file_path
            )

            pages = []

            for page in reader.pages:

                page_text = (
                    page.extract_text()
                )

                if page_text:

                    pages.append(
                        page_text
                    )

            return "\n".join(
                pages
            )

        # TXT
        elif extension == ".txt":

            with open(
                file_path,
                "r",
                encoding="utf-8",
                errors="ignore"
            ) as f:

                return f.read()

        # CSV
        elif extension == ".csv":

            df = pd.read_csv(
                file_path
            )

            return df.to_string(
                index=False
            )

        # Excel
        elif extension == ".xlsx":

            df = pd.read_excel(
                file_path
            )

            return df.to_string(
                index=False
            )

        else:

            raise ValueError(
                f"Unsupported file format: {extension}"
            )

    # =========================================================
    # TEXT CLEANING
    # =========================================================

    def _clean_text(
        self,
        text
    ):

        text = re.sub(
            r"\s+",
            " ",
            text
        )

        return text.strip()

    # =========================================================
    # CHUNKING
    # =========================================================

    def _create_chunks(
        self,
        text,
        chunk_size=500,
        overlap=50
    ):

        words = text.split()

        chunks = []

        start = 0

        while start < len(words):

            end = start + chunk_size

            chunk = " ".join(
                words[start:end]
            )

            if chunk.strip():

                chunks.append(
                    chunk
                )

            start = end - overlap

        return chunks

    # =========================================================
    # QUESTION ANSWERING
    # =========================================================

    def ask(
        self,
        question,
        top_k=5
    ):

        # Generate question embedding
        question_embedding = (
            self.embedding_model.encode(
                question
            )
        )

        # Retrieve relevant chunks
        results = (
            self.chroma_manager.collection.query(
                query_embeddings=[
                    question_embedding
                ],
                n_results=top_k
            )
        )

        documents = (
            results.get(
                "documents",
                [[]]
            )[0]
        )

        metadatas = (
            results.get(
                "metadatas",
                [[]]
            )[0]
        )

        if not documents:

            return {
                "answer": (
                    "I could not find relevant "
                    "research content."
                ),
                "sources": []
            }

        # Combine retrieved chunks
        context = "\n\n".join(
            documents
        )

        # Sources
        sources = []

        for metadata in metadatas:

            if metadata:

                source = metadata.get(
                    "source",
                    "Unknown"
                )

                if source not in sources:

                    sources.append(
                        source
                    )

        # RAG prompt
        prompt = f"""
You are an academic research assistant.

Answer the user's question using ONLY
the research context provided below.

If the answer cannot be found in the
provided research context, say that the
information is not available in the
indexed research documents.

Research Context:
{context}

Question:
{question}

Answer:
"""

        # Generate answer
        answer = self.llm.generate(
            prompt
        )

        return {
            "answer": answer,
            "sources": sources
        }

