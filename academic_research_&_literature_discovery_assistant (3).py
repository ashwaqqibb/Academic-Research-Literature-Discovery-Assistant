class LLMClient:

    def __init__(
        self,
        api_key=(
            settings.OPENROUTER_API_KEY
        ),
        model_name=(
            settings.MODEL_NAME
        )
    ):

        self.api_key = api_key

        self.model_name = model_name

        if self.api_key:

            self.client = OpenAI(
                base_url=(
                    "https://openrouter.ai/api/v1"
                ),
                api_key=self.api_key
            )

            print(
                "Real LLM enabled."
            )

        else:

            self.client = None

            print(
                "Mock LLM enabled."
            )

    def generate(
        self,
        prompt
    ):

        if not self.client:

            return (
                "[MOCK RESPONSE]\n"
                "No API key was configured."
            )

        try:

            response = (
                self.client
                .chat
                .completions
                .create(
                    model=self.model_name,
                    messages=[
                        {
                            "role": "user",
                            "content": prompt
                        }
                    ],
                    temperature=0.2
                )
            )

            return (
                response
                .choices[0]
                .message
                .content
            )

        except Exception as e:

            logger.error(
                f"LLM call failed: {e}"
            )

            return (
                "[MOCK RESPONSE]\n"
                "The LLM request failed."
            )

"""## 14. Research Assistant Service

Combine document validation, extraction, cleaning, chunking, embedding, vector storage, retrieval, and LLM generation into one end-to-end service.
"""

import chromadb
